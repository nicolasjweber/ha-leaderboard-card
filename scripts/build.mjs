import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');

const sourceFiles = [
  'src/period.js',
  'src/filter.js',
  'src/icons.js',
  'src/localize.js',
  'src/styles.js',
  'src/leaderboard-card.js',
  'src/leaderboard-card-editor.js',
  'src/index.js',
];

const pkg = JSON.parse(readFileSync(resolve(rootDir, 'package.json'), 'utf8'));

function stripModuleDirectives(code) {
  return code
    // Remove relative ES module imports
    .replace(/^\s*import\s+[\s\S]*?from\s+['"]\.\/[^'"]+['"];\s*$/gm, '')
    // Remove trailing export { ... }; blocks
    .replace(/^\s*export\s*\{[\s\S]*?\};\s*$/gm, '')
    // Convert `export function|const|let|class` to plain declarations
    .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm, '')
    .trim();
}

const chunks = sourceFiles.map((relPath) => {
  const fullPath = resolve(rootDir, relPath);
  const raw = readFileSync(fullPath, 'utf8');
  return `// --- ${relPath} ---\n${stripModuleDirectives(raw)}`;
});

const banner = `/**
 * ${pkg.name} v${pkg.version}
 * ${pkg.description}
 * License: ${pkg.license}
 * Auto-generated by scripts/build.mjs — edit files in src/ instead.
 */
`;

const bundle = `${banner}\n${chunks.join('\n\n')}\n\nexport {\n  HaLeaderboardCard,\n  HaLeaderboardCardEditor,\n  calculateDeltaFromHistory,\n  calculateDeltaFromStatBuckets,\n  collectCandidateEntityIds,\n  computePeriodBounds,\n  fetchPeriodValues,\n  globToRegExp,\n  normalizeConfig,\n  normalizePeriod,\n  resolveEntities,\n  getLanguage,\n  localize,\n};\n`;

const rootOut = resolve(rootDir, 'ha-leaderboard-card.js');
const distDir = resolve(rootDir, 'dist');
const distOut = resolve(distDir, 'ha-leaderboard-card.js');

mkdirSync(distDir, { recursive: true });
writeFileSync(rootOut, bundle, 'utf8');
writeFileSync(distOut, bundle, 'utf8');

console.log(`Built ${rootOut} (${Buffer.byteLength(bundle, 'utf8')} bytes)`);
console.log(`Built ${distOut} (${Buffer.byteLength(bundle, 'utf8')} bytes)`);
